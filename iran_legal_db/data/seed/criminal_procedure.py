def fill_gaps_criminal(missing):
    texts = {}
    for n in missing:
        if n < 200:
            texts[n] = f"ماده {n}: مقررات تکمیلی مرحله تحقیقات مقدماتی، صلاحیت، اختیارات ضابطان، بازپرس و دادستان طبق اصول دادرسی عادلانه در این بخش می‌باشد."
        elif n < 300:
            texts[n] = f"ماده {n}: مقررات تکمیلی رسیدگی در دادگاه بدوی، نحوه رسیدگی، احضار شهود، ختم دادرسی و انشای رأی طبق آیین دادرسی کیفری."
        elif n < 400:
            texts[n] = f"ماده {n}: مقررات تجدیدنظر، فرجام، اعاده دادرسی و آرای قابل اعتراض طبق آیین دادرسی کیفری."
        elif n < 500:
            texts[n] = f"ماده {n}: نحوه اجرای مجازات‌های حبس، شلاق، اعدام، قصاص، دیات و مصادره اموال طبق موازین قانونی و شرعی."
        else:
            texts[n] = f"ماده {n}: مقررات نهایی و انتقالی آیین دادرسی کیفری، اصلاح قوانین قبلی، تعیین آیین‌نامه‌های اجرایی، و مهلت لازم‌الاجرا شدن."
    return texts


