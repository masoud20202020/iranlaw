F2A = str.maketrans("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩", "01234567890123456789")
A2F = str.maketrans("0123456789٠١٢٣٤٥٦٧٨٩", "۰۱۲۳۴۵۶۷۸۹۰۱۲۳۴۵۶۷۸۹")


def norm_line(line: str) -> str:
    line = re.sub(r"\[([^]]+)\]\([^)]+\)", r"\1", line)
    return re.sub(r"\s+", " ", line.replace("*", "").replace("#", "").replace("‌", " ")).strip()


def clean(text: str) -> str:
    text = re.sub(r"!\[[^]]*\]\([^)]+\)", "", text)
    text = re.sub(r"\[([^]]*)\]\([^)]+\)", r"\1", text)
    text = text.replace("**", "").replace("__", "").replace("\\-", "-")
    text = text.replace("\ufeff", "").replace("\u200e", "").replace("\u200f", "").replace("\u00ad", "").replace("�", "")
    for a, b in {
        "ي": "ی", "ى": "ی", "ك": "ک", "ة": "ه", "ھ": "ه", "ۀ": "هٔ",
        "هیات": "هیأت", "هیئت": "هیأت", "آئين": "آیین", "آئین": "آیین",
        "موسسه": "مؤسسه", "موسسات": "مؤسسات", "مسوول": "مسئول", "مسؤول": "مسئول",
        "بیمه گذار": "بیمه‌گذار", "بیمه گر": "بیمه‌گر", "بیمه نامه": "بیمه‌نامه",
        "حق بیمه": "حق‌بیمه", "زیان دیده": "زیان‌دیده", "لازم الاجرا": "لازم‌الاجرا",
        "تامین": "تأمین", "می باشد": "می‌باشد", "می شود": "می‌شود", "می گردد": "می‌گردد",
        "می نماید": "می‌نماید", "می توانند": "می‌توانند", "می تواند": "می‌تواند",
    }.items():
        text = text.replace(a, b)
    text = re.sub(r"(?m)^\s*#{1,6}\s*", "", text)
    text = re.sub(r"(?m)^\s*فصل\s+[^\n]*$", "", text)
    text = re.sub(r"(?m)^\s*>\s?", "", text)
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r" *\n *", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    text = text.translate(A2F)
    return text.strip(" \n-*‌")


def parse_articles(filename: str, count: int, occurrence: int = 0) -> tuple[tuple[str, str], ...]:
    text = (CACHE / filename).read_text()
    lines = text.splitlines()
    heads: list[tuple[int, int]] = []
    for i, line in enumerate(lines):
        m = re.match(r"^(?:[-–—]\s*)?ماده\s*([۰-۹٠-٩0-9]+)(?![۰-۹٠-٩0-9])", norm_line(line))
        if m:
            heads.append((int(m.group(1).translate(F2A)), i))
    out: list[tuple[str, str]] = []
    for n in range(1, count + 1):
        found = [(j, p) for j, (no, p) in enumerate(heads) if no == n]
        if len(found) <= occurrence:
            raise ValueError(f"{filename}: missing article {n}, occurrence {occurrence}; heads={heads[:80]}")
        j, begin = found[occurrence]
        end = heads[j + 1][1] if j + 1 < len(heads) else len(lines)
        body = clean("\n".join(lines[begin:end]))
        body = re.sub(r"^ماده\s*[۰-۹]+\s*(?:\([^)]*\))?\s*[-ـ–:]?\s*", "", body, count=1)
        for marker in (
            "معاون اول رئیس", "معاون اول رییس", "منبع :", "منبع:", "شما می‌توانید",
            "نسخه word", "نسخه PDF", "مطالب مرتبط", "بیشتر بخوانید:", "نوشته های مشابه", "دیدگاهتان را بنویسید",
            "* برچسب ها:", "برچسب ها:", "مؤسسات حقوقی\nمراجع", "کلانتری ها و پاسگاه ها", "تمامی حقوق مادی",
            "جهت دسترسی به تمامی ضوابط", "شورای‌عالی بیمه در اجرای بند ۵ ماده ۱۷ قانون تأسیس بیمه مرکزی ایران و بیمه‌گری، در جلسه مورخ ۱۳۹۱",
        ):
            if marker in body:
                body = body.split(marker, 1)[0].strip()
        if not body:
            raise ValueError(f"{filename}: empty article {n}")
        out.append((str(n), body))
    return tuple(out)


def replace_row(rows: tuple[tuple[str, str], ...], no: str, text: str) -> tuple[tuple[str, str], ...]:
    return tuple((n, text if n == no else t) for n, t in rows)


